def test_clpo_reads_as_a_lewis_structure_for_water():
    """CLPO gives water two bonds and three lone pairs, as a Lewis structure does."""
    result = _localise(WATER, "6-31g", "clpo")
    bonds = [o for o in result["orbitals"] if o["type"] == "bonding"]
    lone_pairs = [o for o in result["orbitals"] if o["type"] == "lonePairs"]
    assert len(bonds) == 2
    assert len(lone_pairs) == 3
    # Each bond is O-H and carries two electrons; the oxygen keeps the rest.
    assert {tuple(sorted(o["elements"])) for o in bonds} == {("H", "O")}
    assert all(abs(o["occupancy"] - 2.0) < 1e-3 for o in bonds)
    assert all(o["elements"] == ["O"] for o in lone_pairs)
    assert result["valences"] == [2, 1, 1]


def test_lpo_splits_water_lone_pairs_where_clpo_does_not():
    """The two variants differ exactly as JANPA's do, which is the point of both."""
    lpo = _localise(WATER, "6-31g", "lpo")
    clpo = _localise(WATER, "6-31g", "clpo")
    lpo_bonds = sum(1 for o in lpo["orbitals"] if o["type"] == "bonding")
    clpo_bonds = sum(1 for o in clpo["orbitals"] if o["type"] == "bonding")
    assert lpo_bonds == 3 and clpo_bonds == 2
    assert lpo["counts"]["lonePairs"] == 2 and clpo["counts"]["lonePairs"] == 3


def test_localised_orbitals_conserve_electrons():
    """The reported orbitals account for every electron, which the sums confirm."""
    for name, basis in (("water", "6-31g"), ("ammonia", "6-31g"), ("carbon dioxide", "6-31g")):
        mol = gto.M(atom=GEOMETRIES[name], basis=basis, verbose=0)
        for kind in ("lpo", "clpo"):
            result = _localise(GEOMETRIES[name], basis, kind)
            total = sum(result["occupancySummary"][key] for key in KEYS)
            assert abs(total - mol.nelectron) < 1e-4, f"{name} {kind}: {total} != {mol.nelectron}"


def test_localised_orbitals_stay_within_physical_occupancy():
    """The hybrid rotation stays orthonormal, so no occupancy leaves [0, 2]."""
    result = _localise(AMMONIA, "6-31g", "clpo")
    occupancies = [o["occupancy"] for o in result["orbitals"] if o["type"] == "bonding"]
    assert all(-1e-6 < o < 2.0 + 1e-6 for o in occupancies), occupancies
    lone = [o["occupancy"] for o in result["orbitals"] if o["type"] == "lonePairs"]
    assert all(o <= 2.0 + 1e-6 for o in lone), lone


def test_localized_orbitals_method_is_reachable_over_the_bridge():
    """The ``clpo`` and ``lpo`` RPC methods return the localised orbitals."""
    import json

    from pyscf_mobile import bridge

    for method in ("clpo", "lpo"):
        request = {
            "jsonrpc": "2.0",
            "id": 3,
            "method": method,
            "params": {
                "atoms": [
                    {"element": "O", "xyz": [0.0, 0.0, 0.0]},
                    {"element": "H", "xyz": [0.0, -0.757, 0.587]},
                    {"element": "H", "xyz": [0.0, 0.757, 0.587]},
                ],
                "basis": "6-31g",
                "method": "RHF",
            },
        }
        response = json.loads(bridge.handle_json(json.dumps(request)))
        assert "error" not in response, response
        result = response["result"]
        assert result["analysisMethod"] == "LPO/CLPO (JANPA 2.02 port)"
        assert result["kind"] == method.upper()
        expected = REFERENCE[("water", "6-31g")][method.upper()]
        for key, (occupancy, count) in zip(KEYS, expected):
            assert abs(result["occupancySummary"][key] - occupancy) < OCCUPANCY_TOLERANCE
            assert result["counts"][key] == count


def test_unknown_kind_is_rejected():
    """A typo in the variant name is an error, not a silent fallback."""
    import json

    from pyscf_mobile import bridge

    request = {
        "jsonrpc": "2.0",
        "id": 4,
        "method": "clpo",
        "params": {
            "atoms": [
                {"element": "O", "xyz": [0.0, 0.0, 0.0]},
                {"element": "H", "xyz": [0.0, -0.757, 0.587]},
                {"element": "H", "xyz": [0.0, 0.757, 0.587]},
            ],
            "basis": "6-31g",
            "method": "RHF",
            "kind": "nonsense",
        },
    }
    response = json.loads(bridge.handle_json(json.dumps(request)))
    assert "error" in response, response
