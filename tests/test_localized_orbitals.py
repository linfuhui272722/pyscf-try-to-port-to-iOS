"""Localised property-optimised orbitals, checked against the JANPA reference.

Every occupancy and orbital count asserted here was produced by running JANPA
2.02 itself on the same wavefunction -- a MOLDEN written by PySCF, fed to
``java -jar janpa.jar -i <molden>`` -- and reading the LPO and CLPO summary
blocks from its output.  A localisation that looks reasonable but optimises the
wrong functional still yields occupancies near 2 and 0, so the reference values
are the only way to tell a faithful port from a plausible one.

The two variants differ in what they optimise.  LPO maximises the sum of squared
occupancies, which splits lone pairs into bent bonds; CLPO maximises the bonding
and lone-pair occupancies only, which keeps the lone pairs on their own atom and
so reads as a Lewis structure.  Water is the clearest case: LPO finds three
bonding orbitals with two lone pairs, CLPO finds two bonds with three.

Run with ``python tests/run_tests.py``.
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))

from pyscf import gto, scf  # noqa: E402

from pyscf_mobile import localized_orbitals  # noqa: E402

WATER = "O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587"
METHANE = (
    "C 0 0 0; H 0.629 0.629 0.629; H -0.629 -0.629 0.629; "
    "H -0.629 0.629 -0.629; H 0.629 -0.629 -0.629"
)
AMMONIA = "N 0 0 0; H 0 -0.9377 0.3816; H 0.8123 0.4689 0.3816; H -0.8123 0.4689 0.3816"
HYDROGEN_FLUORIDE = "H 0 0 0; F 0 0 0.9171"
CARBON_DIOXIDE = "C 0 0 0; O 0 0 1.16; O 0 0 -1.16"

# JANPA's own summary blocks, as (occupancy sum, orbital count) for
# (bonding, anti-bonding, lone pairs, unoccupied).  Generated by running JANPA
# 2.02 on each wavefunction and reading the two summary blocks; see the module
# docstring for how to reproduce it.
REFERENCE = {
    ("water", "6-31g"): {
        "LPO": ((5.99771, 3), (0.00089, 3), (4.0, 2), (0.0014, 5)),
        "CLPO": ((3.99856, 2), (0.00035, 2), (5.9983, 3), (0.00279, 6)),
    },
    ("water", "cc-pvdz"): {
        "LPO": ((9.99693, 7), (0.00171, 7), (0.0, 0), (0.00136, 10)),
        "CLPO": ((3.99783, 2), (0.00025, 2), (5.99516, 3), (0.00676, 17)),
    },
    ("methane", "6-31g"): {
        "LPO": ((9.99611, 6), (0.00332, 6), (0.0, 0), (0.00057, 5)),
        "CLPO": ((7.99547, 4), (0.00271, 4), (1.99953, 1), (0.00229, 8)),
    },
    ("ammonia", "6-31g"): {
        "LPO": ((7.99877, 5), (0.00123, 5), (2.0, 1), (0.0, 4)),
        "CLPO": ((5.99757, 3), (4e-05, 3), (3.99946, 2), (0.00293, 7)),
    },
    ("hydrogen fluoride", "6-31g"): {
        "LPO": ((4.0, 2), (0.0, 2), (6.0, 3), (-0.0, 4)),
        "CLPO": ((2.0, 1), (-0.0, 1), (7.99905, 4), (0.00095, 5)),
    },
    ("carbon dioxide", "6-31g"): {
        "LPO": ((21.27753, 11), (0.71967, 11), (0.0, 0), (0.00279, 5)),
        "CLPO": ((7.99523, 4), (0.7087, 4), (13.26467, 7), (0.0314, 12)),
    },
}

GEOMETRIES = {
    "water": WATER,
    "methane": METHANE,
    "ammonia": AMMONIA,
    "hydrogen fluoride": HYDROGEN_FLUORIDE,
    "carbon dioxide": CARBON_DIOXIDE,
}

KEYS = ("bonding", "antiBonding", "lonePairs", "rydberg")

# JANPA stops the hybrid optimiser once the target function changes by less than
# 1e-5.  That is the same order as the last digit it prints, so neither program
# lands on a bit-identical optimum: re-running the reference on one unchanged
# wavefunction moves a sum by up to 2e-5 (carbon dioxide's CLPO bonding
# occupancy prints as 7.99523, 7.99522 and 7.99521 depending on the run and the
# BLAS thread count).  A faithful port shares that spread, so the tolerance is
# the optimiser's own threshold with margin -- still two orders of magnitude
# tighter than the sums themselves.
OCCUPANCY_TOLERANCE = 3.0e-5

# LPO maximises the sum of squared occupations, and for a few molecules that
# functional has two optima close enough that the walk lands in either one
# depending on the last bits of the density.  The bits move because BLAS sums a
# contraction in whatever order the thread count implies, so a threaded build
# can give a different answer than a serial one for the same input -- and JANPA
# has the same property, printing both for water in cc-pvdz across runs.  These
# are the alternatives actually observed; a correct port reproduces one of them,
# and the occupancies of the two differ by at most ~0.0014.
LPO_ALTERNATIVES = {
    ("water", "cc-pvdz"): (
        ((9.99693, 7), (0.00171, 7), (0.0, 0), (0.00136, 10)),
        ((9.99829, 8), (0.00171, 8), (0.0, 0), (0.0, 8)),
    ),
    ("carbon dioxide", "6-31g"): (
        ((21.27753, 11), (0.71968, 11), (0.0, 0), (0.00279, 5)),
        ((21.2789, 12), (0.72107, 12), (0.0, 0), (3e-05, 3)),
    ),
}


def _localise(spec, basis, kind):
    mol = gto.M(atom=spec, basis=basis, verbose=0)
    mf = scf.RHF(mol)
    mf.kernel()
    atoms = [
        {"element": mol.atom_symbol(i), "z": mol.atom_charge(i), "xyz": list(mol.atom_coords()[i])}
        for i in range(mol.natm)
    ]
    return localized_orbitals.localized_orbitals(mf, atoms, kind=kind)


def _mismatches(result, expected):
    """The keys of ``expected`` that ``result`` does not reproduce."""
    bad = []
    for key, (occupancy, count) in zip(KEYS, expected):
        if abs(result["occupancySummary"][key] - occupancy) >= OCCUPANCY_TOLERANCE:
            bad.append(
                f"{key} occupancy {result['occupancySummary'][key]} != {occupancy}"
            )
        if result["counts"][key] != count:
            bad.append(f"{key} count {result['counts'][key]} != {count}")
    return bad


def _assert_matches_reference(name, basis, kind):
    result = _localise(GEOMETRIES[name], basis, kind)
    assert result is not None, f"{name}/{basis} {kind} returned nothing"
    candidates = [REFERENCE[(name, basis)][kind.upper()]]
    if kind == "lpo":
        candidates = list(LPO_ALTERNATIVES.get((name, basis), candidates))
    reports = [_mismatches(result, expected) for expected in candidates]
    assert any(not report for report in reports), (
        f"{name}/{basis} {kind}: " + " | ".join("; ".join(r) for r in reports)
    )


def test_water_lpo_matches_janpa():
    _assert_matches_reference("water", "6-31g", "lpo")


