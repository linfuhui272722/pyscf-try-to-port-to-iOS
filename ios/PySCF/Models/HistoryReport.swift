// HistoryReport.swift
//
// Renders saved calculations as plain text.
//
// The report is built from the stored payload through the same model types the
// screens use, so an exported file and the on-screen result cannot disagree
// about what the engine said.
//
// Foundation only: the host test compiles this file to check the output, and
// SwiftUI does not exist there.

import Foundation

enum HistoryReport {

    /// Renders one entry.
    ///
    /// Section order follows how the result is read: what was run, then the
    /// headline energy, then the per-atom detail, then the convergence trace.
    static func text(for entry: HistoryEntry) -> String {
        var lines: [String] = []

        lines.append("PySCF mobile — calculation history")
        lines.append(String(repeating: "=", count: 34))
        lines.append("")

        lines.append(section("Calculation"))
        lines.append(row("Recorded", timestamp(entry.date)))
        lines.append(row("Kind", entry.kind.rawValue))
        lines.append(row("Method", entry.title))
        lines.append(row("Charge", "\(entry.charge)"))
        lines.append(row("Spin", "\(entry.spin)"))
        lines.append(row("Wall time", formatDuration(entry.wallTimeMs)))
        lines.append("")

        lines.append(section("Molecule"))
        let formula = entry.formula
        if !formula.isEmpty { lines.append(row("Formula", formula)) }
        lines.append(entry.atoms)
        lines.append("")

        switch entry.kind {
        case .optimise:
            lines.append(contentsOf: optimisationSections(entry))
        case .scan:
            lines.append(contentsOf: scanSections(entry))
        case .orbitals, .density:
            lines.append(contentsOf: viewSections(entry))
        default:
            lines.append(contentsOf: scfSections(entry))
        }

        let log = entry.payload.value("log") as String? ?? ""
        if !log.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            lines.append(section("Engine log"))
            lines.append(log.trimmingCharacters(in: .whitespacesAndNewlines))
            lines.append("")
        }

        lines.append(String(repeating: "-", count: 34))
        lines.append("Generated by PySCF mobile on \(timestamp(Date()))")
        return lines.joined(separator: "\n") + "\n"
    }

    /// Renders several entries, one after another.
    ///
    /// A blank line and a rule separate records so the file stays readable when
    /// it is scrolled rather than parsed.
    static func text(for entries: [HistoryEntry]) -> String {
        guard !entries.isEmpty else { return "" }
        return entries.map(text(for:)).joined(separator: "\n" + String(repeating: "=", count: 34) + "\n\n")
    }

    /// File name for one entry, e.g. ``pyscf-RHF-sto-3g-20260124-1215.txt``.
    ///
    /// Derived from the record rather than the id, so the name says what the
    /// file holds when it is seen in the Files app or an attachment list.
    static func fileName(for entry: HistoryEntry) -> String {
        var parts = ["pyscf", entry.kind.rawValue, entry.method, entry.basis]
        let formula = entry.formula
        if !formula.isEmpty { parts.append(formula) }
        parts.append(fileStamp(entry.date))
        return parts
            .map { $0.replacingOccurrences(of: "/", with: "-") }
            .joined(separator: "-")
            .appending(".txt")
    }

    /// File name for a bundle of entries.
    static func fileName(count: Int) -> String {
        "pyscf-history-\(count)-\(fileStamp(Date())).txt"
    }

    // MARK: - Per-kind sections

    /// The recipe of a saved 3D picture.
    ///
    /// The mesh is not in the entry, so the report cannot describe the surface
    /// that was drawn -- only what was asked for.  That is still the useful
    /// part: it is what would have to be replayed to get the same picture, and
    /// the numbers that were on screen (the level, the isovalue) are in the
    /// entry's summary line above.
    private static func viewSections(_ entry: HistoryEntry) -> [String] {
        guard let record = ViewRecord(entry.payload) else {
            return [section("Picture"), "Not recorded.", ""]
        }
        var lines: [String] = []
        lines.append(section("Picture"))
        lines.append(row("Reference", record.method))
        switch record {
        case .orbital(let orbital):
            lines.append(row("Orbital", orbital.label))
            lines.append(row("Index", String(orbital.index)))
            lines.append(row("Source", orbital.source))
            lines.append(row("Isovalue", String(format: "%.6f", orbital.isovalue)))
        case .density(let density):
            lines.append(row("Contour", String(format: "%.4f e/bohr³", density.level)))
        }
        lines.append("")
        return lines
    }

    private static func scfSections(_ entry: HistoryEntry) -> [String] {
        let result = ScfResult(entry.payload)
        var lines: [String] = []

        lines.append(section("Energy"))
        lines.append(row("Total energy", formatHartree(result.energy)))
        lines.append(row("Converged", result.converged
                         ? "yes, in \(result.cycles) cycles" : "no"))
        if let correlation = result.correlationEnergy, let scf = result.scfEnergy {
            lines.append(row("SCF reference", formatHartree(scf)))
            lines.append(row("Correlation", formatHartree(correlation)))
        }
        lines.append("")

        lines.append(section("System"))
        lines.append(row("Electrons", "\(result.nElectrons) "
                         + "(alpha \(result.nAlpha), beta \(result.nBeta))"))
        lines.append(row("Basis functions", "\(result.nBasis)"))
        if let homo = result.homo, let lumo = result.lumo {
            lines.append(row("HOMO", formatHartree(homo)))
            lines.append(row("LUMO", formatHartree(lumo)))
        }
        if let gap = result.gap { lines.append(row("Gap", formatEnergyDelta(gap))) }
        lines.append("")

        if !result.orbitalEnergies.isEmpty {
            lines.append(section("Orbital energies"))
            lines.append(tableRow([("MO", 8), ("energy (Ha)", 16), ("occupation", 12)]))
            for (index, energy) in result.orbitalEnergies.enumerated() {
                let occupation = index < result.occupations.count ? result.occupations[index] : 0
                lines.append(tableRow([
                    ("\(index + 1)", 8),
                    (String(format: "%12.6f", energy), 16),
                    (String(format: "%.3f", occupation), 12),
                ]))
            }
            lines.append("")
        }

        if !result.mulliken.perAtom.isEmpty {
            lines.append(section("Mulliken charges (e)"))
            for charge in result.mulliken.perAtom {
                lines.append(row("\(charge.element)\(charge.index + 1)",
                                 String(format: "%+.4f", charge.charge)))
            }
            lines.append("")
        }

        if let npa = result.npa, !npa.perAtom.isEmpty {
            lines.append(section("Natural population analysis (e)"))
            for atom in npa.perAtom {
                lines.append(row("\(atom.element)\(atom.index + 1)",
                                 String(format: "%+.4f", atom.charge)))
                if !atom.configuration.isEmpty {
                    lines.append("        \(atom.configurationText)")
                }
            }
            lines.append(row("Sum rule",
                             String(format: "%.4f / %d", npa.totalPopulation, npa.nElectrons)
                             + (npa.sumRuleOk ? "" : "   (mismatch)")))
            lines.append("")
        }

        if let localized = result.localizedOrbitals, !localized.orbitals.isEmpty {
            lines.append(section("Localized orbitals (\(localized.kind), e)"))
            for orbital in localized.bonds {
                lines.append(row(orbital.label, String(format: "%.4f", orbital.occupancy)))
            }
            for orbital in localized.lonePairs {
                let name = "\(orbital.elements.first ?? "?")"
                    + "\(orbital.centres.first.map { $0 + 1 } ?? 1)"
                lines.append(row("LP \(name)", String(format: "%.4f", orbital.occupancy)))
            }
            if !localized.valences.isEmpty {
                lines.append(row("Valence", localized.valences.map(String.init).joined(separator: ", ")))
            }
            lines.append("")
        }

        if let localization = result.localization, localization.orbitalCount > 0 {
            lines.append(section("Localized orbitals (intrinsic, \(localization.localization))"))
            for orbital in 0..<localization.orbitalCount {
                let centres = localization.centres(ofOrbital: orbital)
                let name = centres.isEmpty
                    ? "delocalised"
                    : centres.map { index in
                        let elements = result.mulliken.perAtom.map(\.element)
                        return index < elements.count ? "\(elements[index])\(index + 1)" : "#\(index + 1)"
                    }.joined(separator: "-")
                lines.append(row("LMO \(orbital + 1)", name))
            }
            lines.append(row("Objective", String(format: "%.8f", localization.objective)))
            lines.append(row("Sweeps", "\(localization.sweeps)"))
            lines.append("")
        }

        if let mayer = result.mayer, !mayer.bonds.isEmpty {
            lines.append(section("Mayer bond orders"))
            for bond in mayer.bonds.sorted(by: { $0.order > $1.order }) {
                lines.append(row(bond.label, String(format: "%.4f", bond.order)))
            }
            lines.append("")
        }

        if result.dipole.vector.count == 3 {
            lines.append(section("Dipole moment"))
            let components = result.dipole.vector.map { String(format: "%+.4f", $0) }
            lines.append(row("Components (D)", components.joined(separator: ", ")))
            lines.append(row("Magnitude (D)", String(format: "%.4f", result.dipole.magnitude)))
            lines.append("")
        }

        return lines
    }

    private static func optimisationSections(_ entry: HistoryEntry) -> [String] {
        let result = OptimisationResult(entry.payload)
        var lines: [String] = []

        lines.append(section("Relaxation"))
        lines.append(row("Converged", result.converged
                         ? "yes, in \(result.steps) of \(result.maxSteps) steps"
                         : "no — \(result.message)"))
        lines.append(row("Final energy", formatHartree(result.energy)))
        lines.append(row("Max gradient", String(format: "%.3e Ha/Bohr", result.maxGradient)))
        lines.append(row("RMS gradient", String(format: "%.3e Ha/Bohr", result.rmsGradient)))
        lines.append(row("Gradient tolerance", String(format: "%.1e Ha/Bohr", result.convTolGrad)))
        if let level = result.gridLevel {
            let relax = result.relaxGridLevel.map { "\($0)" } ?? "default"
            lines.append(row("Grid level", "\(level) (relaxation \(relax))"))
        }
        lines.append("")

        lines.append(section("Initial geometry (Å)"))
        lines.append(result.initialAtoms)
        lines.append("")

        lines.append(section("Optimised geometry (Å)"))
        lines.append(result.optimisedAtoms)
        lines.append("")

        if result.trajectory.count > 1 {
            lines.append(section("Convergence trace"))
            lines.append(tableRow([("Step", 8), ("energy (Ha)", 18), ("max|g|", 14), ("dE (Ha)", 12)]))
            for point in result.trajectory {
                let delta = point.deltaE.map { String(format: "%+.2e", $0) } ?? "—"
                lines.append(tableRow([
                    ("\(point.step)", 8),
                    (String(format: "%14.8f", point.energy), 18),
                    (String(format: "%.2e", point.maxGrad), 14),
                    (delta, 12),
                ]))
            }
            lines.append("")
        }

        return lines
    }

    private static func scanSections(_ entry: HistoryEntry) -> [String] {
        let result = BondScanResult(entry.payload)
        var lines: [String] = []

        lines.append(section("Bond scan — \(result.label)"))
        if let r = result.minimumR, let e = result.minimumEnergy {
            lines.append(row("Minimum", "\(formatLength(r))  \(formatHartree(e))"))
        }
        lines.append(row("Distance (Å)", "energy (Ha)"))
        for point in result.points {
            let value = point.energy.map(formatHartree) ?? "failed: \(point.error ?? "unknown")"
            lines.append(row(formatLength(point.r), value))
        }
        lines.append("")
        return lines
    }

    // MARK: - Layout helpers

    private static func section(_ title: String) -> String {
        "\(title)\n" + String(repeating: "-", count: title.count)
    }

    /// A label/value row. The label is padded so values line up in a column.
    private static func row(_ columns: String...) -> String {
        guard let last = columns.last else { return "" }
        let head = columns.dropLast().map { column in
            column.count >= 22 ? column + " " : column.padding(toLength: 22, withPad: " ", startingAt: 0)
        }
        return (head + [last]).joined().trimmingCharacters(in: .whitespaces)
    }

    /// A table row with fixed column widths, for the numeric sections.
    private static func tableRow(_ columns: [(String, Int)]) -> String {
        columns.map { $0.0.padding(toLength: $0.1, withPad: " ", startingAt: 0) }
            .joined()
            .trimmingCharacters(in: .whitespaces)
    }

    private static func timestamp(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = "yyyy-MM-dd HH:mm:ss"
        return formatter.string(from: date)
    }

    private static func fileStamp(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = "yyyyMMdd-HHmmss"
        return formatter.string(from: date)
    }
}
